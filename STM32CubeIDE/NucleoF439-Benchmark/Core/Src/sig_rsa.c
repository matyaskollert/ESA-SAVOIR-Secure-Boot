/*
 * sig_rsa.c  —  RSA-PSS + SHA-256 benchmark implementation
 *
 * Supports RSA-3072 (384-byte sig) and RSA-4096 (512-byte sig).
 * The active variant is selected at compile time via BENCHMARK_ALGO:
 *
 *   BENCHMARK_ALGO = ALGO_RSA_3072  →  RSA-3072-PSS, sig=384 B, pub=~423 B
 *   BENCHMARK_ALGO = ALGO_RSA_4096  →  RSA-4096-PSS, sig=512 B, pub=~550 B
 *
 * wolfSSL config required:
 *   WC_RSA_PSS        (enable RSA-PSS padding mode)
 *   !NO_RSA           (RSA enabled — this is the default)
 *
 * Key update workflow
 * ───────────────────
 * 1. Generate keys with the benchmark tool:
 *      cd benchmark_tool && ./benchmark_tool --image image.bin --force-keygen
 * 2. Convert each public key:
 *      python uploader/pem_to_c_array.py keys/RSA-3072-PSS_public.der rsa3072PubKey
 *      python uploader/pem_to_c_array.py keys/RSA-4096-PSS_public.der rsa4096PubKey
 * 3. Paste each output into rsa3072PubKey[] / rsa4096PubKey[] below.
 *    Both keys are stored permanently — no re-paste needed when switching sizes.
 */

