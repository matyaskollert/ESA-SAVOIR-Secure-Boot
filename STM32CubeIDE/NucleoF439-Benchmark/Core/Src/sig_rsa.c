// Scratch buffer for RSA-PSS verify: must be at least RSA_SIG_SIZE bytes.
static byte s_rsaOutBuf[RSA_SIG_SIZE];

static RsaKey rsaKey;

static int16_t algo_init(void)
{
    word32 idx = 0;
    int ret = wc_InitRsaKey(&rsaKey, NULL);
    if (ret != 0) { printf("wc_InitRsaKey: %d\r\n", ret); return ret; }

    ret = wc_RsaPublicKeyDecode(pubKey, &idx, &rsaKey, sizeof(pubKey));
    if (ret != 0)
    {
        printf("wc_RsaPublicKeyDecode: %d\r\n", ret);
        wc_FreeRsaKey(&rsaKey);
        return ret;
    }
    return 0;
}

static int16_t algo_verify(const byte* msg, uint32_t msgLen,
                           const byte* sig, uint32_t sigLen)
{
    // Compute the SHA-256 digest of the message.
    byte digest[WC_SHA256_DIGEST_SIZE];
    Sha256 sha;
    wc_InitSha256(&sha);
    wc_Sha256Update(&sha, msg, msgLen);
    wc_Sha256Final(&sha, digest);

    // Step 1: RSA public-key operation plus PSS unpadding decode.
    int ret = wc_RsaPSS_Verify_ex((byte*)sig, (word32)sigLen,
                                  s_rsaOutBuf, sizeof(s_rsaOutBuf),
                                  WC_HASH_TYPE_SHA256, WC_MGF1SHA256,
                                  WC_SHA256_DIGEST_SIZE,
                                  &rsaKey);
    if (ret < 0) { printf("wc_RsaPSS_Verify_ex: %d\r\n", ret); return 0; }

    // Step 2: Verify that the PSS padding encodes the expected digest.
    ret = wc_RsaPSS_CheckPadding_ex(digest, WC_SHA256_DIGEST_SIZE,
                                    s_rsaOutBuf, (word32)ret,
                                    WC_HASH_TYPE_SHA256,
                                    WC_SHA256_DIGEST_SIZE, 0);
    if (ret != 0) { printf("wc_RsaPSS_CheckPadding_ex: %d\r\n", ret); return 0; }
    return 1;
}

static void algo_cleanup(void)
{
    wc_FreeRsaKey(&rsaKey);
}

const sig_algo_t g_algo = {
    .name    = RSA_NAME,
    .init    = algo_init,
    .verify  = algo_verify,
    .cleanup = algo_cleanup,
    .sig_len = RSA_SIG_SIZE
};

